// Writes packages/conformance/catalogue.json (machine-readable, the seed for
// profile.json) and packages/conformance/catalogue.md (the same as tables) from
// scripts/conformance/catalogue.ts. Coverage columns come from manifest.json
// when it exists.
//
//   corepack pnpm tsx scripts/conformance/emit-catalogue.ts

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOGUE, CATALOGUE_VERSION, DECISIONS, TODAY_LEGEND, type Feature } from './catalogue';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const dir = path.join(root, 'packages', 'conformance');

/** packages/core/profile.json, when this branch has it, is the single source: its statuses, decisions and neutralisations win. */
function overlayProfile(): string[] {
  const file = path.join(root, 'packages', 'core', 'profile.json');
  if (!fs.existsSync(file)) return [];
  const profile = JSON.parse(fs.readFileSync(file, 'utf8')) as { profile: number; decisions: Record<string, string>; features: Feature[] };
  const notes: string[] = [];
  const byId = new Map(profile.features.map((f) => [f.id, f]));
  for (const f of CATALOGUE) {
    const p = byId.get(f.id);
    if (!p) { notes.push(`${f.id}: not in profile.json`); continue; }
    f.status = p.status; f.decision = p.decision;
    if (p.neutralise) f.neutralise = p.neutralise; else delete f.neutralise;
  }
  for (const id of byId.keys()) if (!CATALOGUE.some((f) => f.id === id)) notes.push(`${id}: in profile.json, not in the catalogue`);
  Object.assign(DECISIONS, profile.decisions);
  return notes;
}

export function emitCatalogue(): void {
  fs.mkdirSync(dir, { recursive: true });
  const profileNotes = overlayProfile();
  if (profileNotes.length) console.log('profile.json: ' + profileNotes.join('; '));
  const ids = new Set<string>();
  for (const f of CATALOGUE) {
    if (ids.has(f.id)) throw new Error('duplicate catalogue id ' + f.id);
    ids.add(f.id);
    if (!DECISIONS[f.decision]) throw new Error(`${f.id}: unknown decision ${f.decision}`);
  }
  const manifestFile = path.join(dir, 'manifest.json');
  const tests: { id: string; covers: string[] }[] = fs.existsSync(manifestFile) ? JSON.parse(fs.readFileSync(manifestFile, 'utf8')).tests : [];
  const coveredBy = new Map<string, string[]>();
  for (const t of tests) for (const c of t.covers) coveredBy.set(c, [...(coveredBy.get(c) ?? []), t.id]);
  for (const c of coveredBy.keys()) if (!ids.has(c)) throw new Error(`manifest covers unknown catalogue id ${c}`);

  const json = {
    $comment: 'Generated by scripts/conformance/emit-catalogue.ts from scripts/conformance/catalogue.ts. The seed for profile.json: status in/out/candidate per feature, the decision it comes from, what the pipeline of the tag does with it (today: profile 1 enforced, SDK v1), and the keys a validator/shim table matches on.',
    version: CATALOGUE_VERSION,
    decisions: DECISIONS,
    features: CATALOGUE,
  };
  fs.writeFileSync(path.join(dir, 'catalogue.json'), JSON.stringify(json, null, 2) + '\n');

  const count = (pred: (f: Feature) => boolean) => CATALOGUE.filter(pred).length;
  const areas = [...new Set(CATALOGUE.map((f) => f.area))];
  const md: string[] = [
    '# Widget profile feature catalogue',
    '',
    `Generated from \`scripts/conformance/catalogue.ts\` (\`corepack pnpm tsx scripts/conformance/emit-catalogue.ts\`); machine-readable: [catalogue.json](catalogue.json). ${CATALOGUE.length} features: ${count((f) => f.status === 'in')} in (${count((f) => f.status === 'in' && !!f.conditional)} conditional on every renderer drawing them), ${count((f) => f.status === 'out')} out, ${count((f) => f.status === 'candidate')} candidates. Decision \`proposed\` marks this catalogue's own proposals (${count((f) => f.decision === 'proposed')}).`,
    '',
    '| Area | Features | in | out | candidate | covered by tests |',
    '|---|---|---|---|---|---|',
    ...areas.map((a) => {
      const fs_ = CATALOGUE.filter((f) => f.area === a);
      return `| ${a} | ${fs_.length} | ${fs_.filter((f) => f.status === 'in').length} | ${fs_.filter((f) => f.status === 'out').length} | ${fs_.filter((f) => f.status === 'candidate').length} | ${fs_.filter((f) => coveredBy.has(f.id)).length} |`;
    }),
    `| **all** | ${CATALOGUE.length} | ${count((f) => f.status === 'in')} | ${count((f) => f.status === 'out')} | ${count((f) => f.status === 'candidate')} | ${count((f) => coveredBy.has(f.id))} |`,
    '',
    'Columns: **status** (in / out / candidate; "in*" = in if every renderer draws it, D3a), **decision** (see the legend at the end), **today** (what the pipeline of the tag does with it under `strict`: profile 1 enforced, SDK v1; legend below), **tests** (conformance widgets that judge it).',
    '',
  ];
  for (const a of areas) {
    md.push(`## ${a}`, '', '| ID | Feature | Status | Decision | Today | Out: neutralised as | Tests |', '|---|---|---|---|---|---|---|');
    for (const f of CATALOGUE.filter((x) => x.area === a)) {
      const st = f.status === 'in' && f.conditional ? 'in*' : f.status;
      // A | inside a cell (light|medium|heavy) would end it.
      const cell = (t: string) => t.replace(/\|/g, '\\|');
      const note = f.note ? `<br><sub>${cell(f.note)}</sub>` : '';
      md.push(`| \`${f.id}\` | ${cell(f.title)}${note} | ${st} | ${f.decision} | ${f.today} | ${cell(f.neutralise ?? '')} | ${(coveredBy.get(f.id) ?? []).join(', ')} |`.replace(/\n/g, ' '));
    }
    md.push('');
  }
  md.push('## Today', '', ...Object.entries(TODAY_LEGEND).map(([k, v]) => `- **${k}**: ${v}`), '');
  md.push('## Decisions', '', ...Object.entries(DECISIONS).map(([k, v]) => `- **${k}**: ${v}`), '');
  fs.writeFileSync(path.join(dir, 'catalogue.md'), md.join('\n'));
  console.log(`catalogue: ${CATALOGUE.length} features (in ${count((f) => f.status === 'in')}, out ${count((f) => f.status === 'out')}, candidate ${count((f) => f.status === 'candidate')}, proposed ${count((f) => f.decision === 'proposed')}), covered ${count((f) => coveredBy.has(f.id))}`);
}

if (import.meta.url === `file://${process.argv[1]}`) emitCatalogue();
